// `./gradlew moduleGraph` (or `make graph`) → docs/module-graph.md, a Mermaid rendering of the actual
// project-to-project dependencies. The modularization guardrail from the target-architecture doc: a generated
// graph is the cheapest guard against layering drift, and it is what replaced the old LayeringRulesTest.
// Reads DECLARED dependencies (no configuration resolution), so it works for the KMP modules too.
val moduleGraph = tasks.register("moduleGraph") {
    group = "documentation"
    description = "Regenerates docs/module-graph.md from the projects' declared dependencies."
    notCompatibleWithConfigurationCache("reads every module's declared project dependencies")
    val output = layout.projectDirectory.file("docs/module-graph.md").asFile
    val edges = provider {
        subprojects
            // Skip the path-only container projects (":core", ":data:speech") — they have no build file
            // and exist only because their children are nested under them.
            .filter { it.buildFile.exists() }
            .sortedBy { it.path }
            .map { sub ->
                sub.path to sub.configurations
                    .flatMap { conf -> conf.dependencies.withType(ProjectDependency::class.java) }
                    .map { it.path }
                    // The KMP/AGP plugins add a self-reference to some configurations; it is not an edge.
                    .filter { it != sub.path }
                    .distinct()
                    .sorted()
            }
    }
    outputs.file(output)
    // These read the source tree itself, not a declared input set — always regenerate rather than report a
    // stale map as up-to-date.
    outputs.upToDateWhen { false }
    doLast {
        val lines = buildString {
            appendLine("# Module graph")
            appendLine()
            appendLine("Generated by `./gradlew moduleGraph` — do not edit by hand. Every arrow points from a")
            appendLine("module to something it depends on; see ARCHITECTURE.md §2 for what the direction means.")
            appendLine()
            appendLine("```mermaid")
            appendLine("graph TD")
            edges.get().forEach { (path, deps) ->
                if (deps.isEmpty()) appendLine("  ${path.nodeId()}[\"$path\"]")
                deps.forEach { dep -> appendLine("  ${path.nodeId()}[\"$path\"] --> ${dep.nodeId()}[\"$dep\"]") }
            }
            appendLine("```")
        }
        output.parentFile.mkdirs()
        output.writeText(lines)
        logger.lifecycle("Wrote ${output.relativeTo(rootDir)}")
    }
}

fun String.nodeId(): String = trimStart(':').replace(':', '_').replace('-', '_')

