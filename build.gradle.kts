// `./gradlew schemaCheck` — a persisted-schema edit without a version bump breaks every existing install.
//
// Every `<module>/schemas/` directory is a ledger: version N's file is written once and never again, and a
// schema change shows up as a NEW N+1.json. Two kinds of file live there:
//
//  - Room exported schemas (`schemas/<Database FQN>/N.json`). `fallbackToDestructiveMigration` fires on a
//    MISSING MIGRATION PATH, not on an identity-hash mismatch, so editing an entity while
//    `@Database(version)` stays put throws `Room cannot verify the data integrity` at open. The bump is also
//    what makes the destructive fallback do its job.
//  - Persisted-document schemas (`schemas/documents/<name>/N.json`). A `PersistedDocument` whose shape
//    changes without its `version` moving decodes old bytes as the new shape. Bump `version` in code and let
//    `PersistedDocumentSchemaTest` write the new N.json.
//
// Either way, a committed N.json that shows up as Modified is the bug.

tasks.register("schemaCheck") {
    group = "verification"
    description = "Fails if a committed schema JSON (Room or persisted document) was rewritten, not versioned."
    notCompatibleWithConfigurationCache("walks every module's schemas/ directory")
    val schemaDirs = provider {
        subprojects.filter { it.buildFile.exists() }
            .map { File(it.projectDir, "schemas") }
            .filter { it.isDirectory }
            .map { it.relativeTo(rootDir).invariantSeparatorsPath }
    }
    val root = rootDir
    outputs.upToDateWhen { false }
    doLast {
        val dirs = schemaDirs.get()
        if (dirs.isEmpty()) return@doLast
        val diff = runCatching {
            val process = ProcessBuilder(listOf("git", "diff", "--name-status", "HEAD", "--") + dirs)
                .directory(root)
                .redirectErrorStream(false)
                .start()
            val text = process.inputStream.bufferedReader().readText()
            if (process.waitFor() != 0) null else text
        }.getOrNull()
        if (diff == null) {
            logger.lifecycle("schemaCheck: no git checkout to compare against — skipped.")
            return@doLast
        }
        val rewritten = diff.lineSequence()
            .mapNotNull { line ->
                val parts = line.split('\t')
                if (parts.size >= 2 && parts[0].startsWith("M") && parts[1].endsWith(".json")) parts[1] else null
            }
            .toList()
        if (rewritten.isEmpty()) {
            logger.lifecycle("schemaCheck: no committed schema file was rewritten.")
            return@doLast
        }
        throw GradleException(
            buildString {
                appendLine("${rewritten.size} committed schema file(s) were rewritten in place:")
                rewritten.forEach { appendLine("  - $it") }
                appendLine()
                appendLine("Version N's schema file is written once and never edited. Add N+1 instead:")
                appendLine()
                appendLine("  Room (schemas/<Database>/N.json): bump `@Database(version = N + 1)` and let KSP")
                appendLine("  write the new N.json. Room's destructive fallback only fires on a missing")
                appendLine("  migration PATH — at the same version it throws `IllegalStateException: Room")
                appendLine("  cannot verify the data integrity` on every existing install.")
                appendLine()
                appendLine("  Persisted document (schemas/documents/<name>/N.json): bump the document's")
                appendLine("  `PersistedDocument.version` in code and let `PersistedDocumentSchemaTest` write")
                appendLine("  the new N.json.")
                appendLine()
                appendLine("Then restore the old file(s):")
                appendLine("  git checkout -- ${rewritten.joinToString(" ")}")
            }
        )
    }
}

