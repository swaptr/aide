// Static analysis. There was none: no detekt, no ktlint, no lint config. Applied to every module from here
// (rather than a line in 22 build files) with ONE curated ruleset — see config/detekt/detekt.yml for why the
// style rulesets are off and the defect-shaped ones are on.

subprojects {
    // Not :server. Spring's dependency-management plugin applies its BOM to EVERY configuration, detekt's
    // included, which drags the project's Kotlin onto detekt's own classpath — and detekt 1.23 refuses to
    // run against a Kotlin it was not compiled with. `resolutionStrategy.force` does not win against that
    // BOM. It costs little: :server is a 165-line service that shares no code with the app, and it has its
    // own compiler strictness (-Xjsr305=strict) plus Spring's own analysis.
    if (path == ":server") return@subprojects
    apply(plugin = "io.gitlab.arturbosch.detekt")
    extensions.configure<io.gitlab.arturbosch.detekt.extensions.DetektExtension> {
        config.setFrom(rootProject.layout.projectDirectory.file("config/detekt/detekt.yml"))
        buildUponDefaultConfig = true
        parallel = true
        // Every source set, including tests: a swallowed cancellation in a test fixture is still a defect.
        source.setFrom(files("src"))
    }
    // detekt runs on its OWN Kotlin, not the project's. Without this, `:server` fails outright — Spring's
    // dependency-management plugin applies its BOM to every configuration, including detekt's, and detekt
    // refuses to run against a Kotlin version it was not compiled with.
    tasks.withType<io.gitlab.arturbosch.detekt.Detekt>().configureEach {
        jvmTarget = "21"
        reports {
            html.required.set(true)
            xml.required.set(false)
            sarif.required.set(false)
            txt.required.set(false)
            md.required.set(false)
        }
    }
}

